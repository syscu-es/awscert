// Merges scripts/kb-data/<CODE>.json (scraped domains/task statements) with
// <CODE>.manual.json + <CODE>.questions.json (question banks) into a single static
// src/data/certifications.js that the app imports directly — no runtime network
// dependency. Re-run after scraping/generating new content, before `vite build`
// (wired as the "prebuild" npm script).
//
// Usage: node scripts/build-static-kb.mjs

import { writeFile, readFile, readdir } from 'node:fs/promises';

const KB_DIR = new URL('./kb-data/', import.meta.url);
const OUT_FILE = new URL('../src/data/certifications.js', import.meta.url);

async function readJsonIfExists(url) {
  try {
    return JSON.parse(await readFile(url, 'utf-8'));
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw err;
  }
}

async function main() {
  const files = (await readdir(KB_DIR)).filter(
    (f) => f.endsWith('.json') && !f.endsWith('.questions.json') && !f.endsWith('.manual.json')
  );

  const certifications = {};
  let globalId = 1;

  for (const file of files.sort()) {
    const code = file.replace('.json', '');
    const kb = JSON.parse(await readFile(new URL(file, KB_DIR), 'utf-8'));

    const manual = (await readJsonIfExists(new URL(`${code}.manual.json`, KB_DIR))) || [];
    const generated = (await readJsonIfExists(new URL(`${code}.questions.json`, KB_DIR))) || [];
    const allQuestions = [...manual, ...generated];

    certifications[code] = {
      name: kb.name,
      level: kb.level,
      domains: kb.domains.map((d) => ({ number: d.number, title: d.title, weightPct: d.weightPct })),
      questionBank: allQuestions.map((q) => ({
        id: globalId++,
        domain: q.domainNumber,
        text: q.text,
        options: q.options,
        correct: q.correct,
        type: q.type,
        explanation: q.explanation,
      })),
    };
  }

  const banner =
    '// AUTO-GENERATED by scripts/build-static-kb.mjs from scripts/kb-data/*.json — do not edit by hand.\n' +
    '// To refresh: npm run kb:scrape (rescrape AWS exam guides) -> generate new questions ' +
    '(npm run kb:generate, or ask Claude to write <CODE>.questions.json directly) -> npm run kb:build.\n\n';
  const body = `export const CERTIFICATIONS = ${JSON.stringify(certifications, null, 2)};\n`;

  await writeFile(OUT_FILE, banner + body);

  const certCount = Object.keys(certifications).length;
  const questionCount = Object.values(certifications).reduce((sum, c) => sum + c.questionBank.length, 0);
  console.log(`Wrote src/data/certifications.js — ${certCount} certifications, ${questionCount} questions.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
